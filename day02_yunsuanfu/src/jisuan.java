public class jisuan {
    public static void main(String[] args){
        print1(10,3);
    }

    public static void print1(int a, int b){
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
        //取小数
        System.out.println((double)a/b);
        System.out.println(1.0*a/b);
        System.out.println(a%b);
    }
}
